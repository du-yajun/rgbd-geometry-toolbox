fake_rgb = np.stack([depth, depth, depth], axis=-1)
print("fake_rgb.shape =", fake_rgb.shape, " # (高, 宽, 通道数)")
print("fake_rgb[1, 2] =", fake_rgb[1, 2], " # 第 1 行第 2 列的三个通道值相同")
