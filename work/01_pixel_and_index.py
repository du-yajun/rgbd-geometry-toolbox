plt.figure(figsize=(4.5, 3.8))
plt.imshow(depth, cmap="viridis")
plt.title("depth[row, col] = row * 10 + col")
plt.xlabel("col = u  (向右增大) ->")
plt.ylabel("row = v  (向下增大)")
plt.colorbar(label="depth value")
plt.tight_layout()
plt.savefig(OUT_DIR / "01_pixel_grid.png", dpi=120)
plt.close()
print("已保存:", OUT_DIR / "01_pixel_grid.png")
print()


