# 5. 假装是彩色图：彩色图 = 三张同尺寸的二维图叠在最后一个轴上
#    真实彩色图是 (H, W, 3) 的 uint8（取值 0~255），深度图通常是 (H, W) 的单通道。
#    两者形状不同，这就是阶段 2 检查 shape 时要盯的点。
