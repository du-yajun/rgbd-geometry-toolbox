"""任务 1：像素坐标 (u, v) 与数组下标 [row, col] 的对应关系。

运行方式：
    conda activate rgbd
    python work/01_pixel_and_index.py

一句话总结这个脚本要证明的事：
    图像数组的第 0 轴是竖直方向（v / row），第 1 轴是水平方向（u / col），
    所以「像素坐标 (u, v)」翻译成数组下标要写成 [v, u]，顺序是反的。
"""

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

# 输出目录：用脚本自身的位置反推项目根目录，换台电脑、换个目录也照样能跑。
# Path(__file__) = .../work/01_pixel_and_index.py
# .parents[0]    = .../work
# .parents[1]    = 项目根目录
OUT_DIR = Path(__file__).resolve().parents[1] / "outputs"
OUT_DIR.mkdir(exist_ok=True)


# ---------------------------------------------------------------------------
# 1. 构造一个 4 行 5 列的数组，让 depth[row, col] == row * 10 + col
#    用广播代替双层 for 循环：形状 (H, 1) 与 (1, W) 相加会自动扩展成 (H, W)
# ---------------------------------------------------------------------------
H, W = 4, 5

row = np.arange(H).reshape(H, 1)  # 形状 (4, 1)，沿第 0 轴变化 -> 竖直方向
col = np.arange(W).reshape(1, W)  # 形状 (1, 5)，沿第 1 轴变化 -> 水平方向
depth = row * 10 + col            # 广播成 (4, 5)

print("depth.shape =", depth.shape, " # (行数 H, 列数 W) = (高, 宽)")
print("depth.dtype =", depth.dtype)
print()


# ---------------------------------------------------------------------------
# 2. 同一份数据，两种读法：
#    数组下标 [row, col]  <->  像素坐标 (u, v)
#    桥梁：u = col，v = row   =>   读某个像素的深度要写 depth[v, u]
# ---------------------------------------------------------------------------
print("depth[2, 3] =", depth[2, 3])
print("  ^ 数组下标 [row=2, col=3]，即像素坐标 (u=3, v=2)")

print("depth[3, 2] =", depth[3, 2])
print("  ^ 数组下标 [row=3, col=2]，即像素坐标 (u=2, v=3)")

print("  -> 两个值不同：下标顺序写反时通常不报错，只会读到别的像素")
print()


# ---------------------------------------------------------------------------
# 3. 用切片验证两个轴的方向：
#    固定第 1 轴(col/u) 只留一列 -> 竖着的一列，长度 = H
#    固定第 0 轴(row/v) 只留一行 -> 横着的一行，长度 = W
#    两个结果长度不同，正好说明第 0 轴是竖直方向。
# ---------------------------------------------------------------------------
print("depth[:, 3] =", depth[:, 3])
print("  ^ 固定 col/u=3，沿第 0 轴取 -> 竖着的一列，共", depth[:, 3].shape[0], "个元素")

print("depth[2, :] =", depth[2, :])
print("  ^ 固定 row/v=2，沿第 1 轴取 -> 横着的一行，共", depth[2, :].shape[0], "个元素")
print()


# ---------------------------------------------------------------------------
# 4. 存图（matplotlib 样板代码）
#    imshow 默认把第 0 轴画在竖直方向、且向下增大，原点在左上角。
# ---------------------------------------------------------------------------
# matplotlib 默认字体（DejaVu Sans）不含中文字形，直接写中文标签会变成方块。
# 这里从系统字体里挑一个可用的中文字体；找不到就保持默认（英文标签不受影响）。
