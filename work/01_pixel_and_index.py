#
# Q1. depth[2, 3] 对应的像素坐标 (u, v) 是多少？为什么不是 (3, 2)？
#     答：(u, v) = (3, 2)。
#     np.ndarray 的索引顺序是 [第 0 轴, 第 1 轴]，即 [row, col]；
#     而图像数组的第 0 轴是竖直方向（v）、第 1 轴是水平方向（u）。
#     所以 [2, 3] 读作「row=2, col=3」，翻译成像素坐标就是 u=3, v=2。
#     实测 depth[2, 3] = 23 = 2*10 + 3，与 row*10 + col 的定义自洽；
#     而 depth[3, 2] = 32 是另一个像素 —— 两者不同，正是「没写反」的证据。
#
# Q2. 用 imshow 看深度图时，行号 v 向下增大，「图像的上面」对应真实世界的哪个方向？
#     答：在 OpenCV / Open3D 常用的相机坐标系里：X 向右、Y 向下、Z 向前（沿光轴）。
#     v 与 Y 同向，所以 v 小（图像上方）对应 Y 为负的方向，即相机坐标系的 -Y。
#     这也解释了为什么相机坐标系特意把 Y 轴朝下：让 v 轴与它同向，
#     投影公式 v = fy * Y / Z + cy 里的符号就是正的，不必额外加负号。
#     要记住这是「人为约定」，不是物理必然：如果某个数据集用的是 Y 朝上的约定，
#     公式符号就得跟着改。
#     [待验证] 阶段 2 拿到真实 RGB-D 深度图后，再用真实数据确认一次方向。
#
# Q3. 形状 (480, 640, 3) 的彩色图，u 和 v 的最大值分别是多少？
#     答：u_max = 639（u 跟宽度 W=640 走），v_max = 479（v 跟高度 H=480 走）。
#     整数坐标代表像素「中心」，所以合法范围是 0 ... W-1 和 0 ... H-1，不是 0 ... W。
#     这种差一位的地方，以后填内参时还会遇到：
#     cx 是水平主点（≈ W/2，跟 u 同族），cy 是竖直主点（≈ H/2，跟 v 同族）。
#
# Q4. 把 depth[v, u] 错写成 depth[u, v]，什么时候报错、什么时候静默算错？
#     答：以 480x640 的图为例，depth.shape = (480, 640)，
#         第 0 轴合法下标 0..479，第 1 轴合法下标 0..639。
#         - 当 u >= 480 时：第 0 轴越界 -> 抛 IndexError。
#         - 当 u < 480 时（绝大多数像素）：不报错，但取到的是 [u, v] 这个位置的
#           深度值，等于把「横向偏移」和「纵向偏移」对调了。
#           此时数组形状完全正确、程序照常跑完，只是结果错了 —— 静默错误。
#         - 特例：u == v 的像素（对角线附近）恰好取到正确值，
#           所以抽检时要特意挑 u != v 的像素，否则抽查等于没做。
#     防护手段：
#         1) 函数入口先断言 arr.shape == (H, W)，把形状错误挡在最外层；
#         2) 挑几个已知位置的像素手工核对数值；
#         3) 阶段 3/4 再加一条更强的检查：反投影得到三维点、再投影回像素，
#            看能否回到原来的 (u, v)。这条能同时抓住方向、单位、内参三类错误。
#
# 本任务真正想让你记住的结论：
#     程序不报错 != 结果正确。行列互换、RGB/BGR、深度单位、
#     内参分辨率不匹配这几类错误，都属于「能跑完但算错」，
#     只能靠主动设计的检查来发现。
